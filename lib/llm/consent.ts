import type { OfferVerdict } from '@/lib/engine/state'

/**
 * Согласие, которого не было.
 *
 * Решение по пакету принимает код, модель его только проговаривает. Но запрет
 * в промпте — это просьба, а не гарантия: на живом прогоне вторая сторона
 * сказала «Скидку по земле я принимаю» в ходе, где пакета не было вовсе.
 * В соглашении ничего не изменилось, а человек услышал, что договорились.
 * Реплика и документ разошлись — и ровно в том месте, где продукт обещает,
 * что модель говорит только то, что уже решено.
 *
 * Поэтому реплика проверяется кодом. Нашлось согласие без вердикта `accept` —
 * ход переписывается (см. `app/api/turn/route.ts`).
 *
 * Детектор намеренно узкий: он ищет согласие на условия, а не любое «да».
 * «Согласен, что сроки важны», «принимаю ваши доводы» и условное «если дадите
 * март — согласен» согласием на сделку не считаются.
 */

/**
 * `\b` в JavaScript знает только латиницу: для кириллицы граница слова
 * не находится никогда. Поэтому границы слов здесь явные.
 */
const L = '(?<![а-яa-z0-9])'
const R = '(?![а-яa-z0-9])'
const w = (src: string) => new RegExp(L + src + R)

/** Фразы, которые закрывают сделку целиком. Недопустимы ни при каком вердикте, кроме `accept`. */
const CLOSING = [
  w('договорились'),
  w('по рукам'),
  w('заметано'),
  w('сделка (заключена|состоялась)'),
  w('(готов[аы]?|можем|давайте) (подписывать|подписать|подписываем|фиксировать|зафиксировать)'),
  w('(подписываем|фиксируем|фиксируйте)'),
]

/** Согласие на условия. Недопустимо, когда пакета не было или он отвергнут. */
const ACCEPTING = [
  w('принима(ю|ем)'),
  w('соглас(ен|на|ны)'),
  w('соглаша(юсь|емся)'),
  w('(беру|берем)'),
  w('нас устраивает'),
  w('меня устраивает'),
]

/** Согласие с мыслью, а не с условиями. */
const NOT_A_DEAL = [
  new RegExp(L + 'соглас(ен|на|ны),?\\s+(с\\s+(вами|тем|этим)|что|в том)'),
  new RegExp(L + 'принима(ю|ем),?\\s+(к сведению|ваш[иа]?\\s+(довод|аргумент|замечан|позици)|аргумент|довод|во внимание)'),
]

const NEGATION = new RegExp(L + '(не|ни|нельзя|никак)\\s+(\\S+\\s+){0,2}$')

export interface ConsentHit {
  /** Предложение реплики, в котором нашлось согласие. */
  sentence: string
  phrase: string
}

function norm(text: string) {
  return text.toLowerCase().replace(/ё/g, 'е')
}

/**
 * Ищет в реплике согласие, на которое у модели не было решения движка.
 * Возвращает `null`, если реплика чистая или вердикт `accept`.
 */
export function detectConsent(reply: string, verdict?: OfferVerdict): ConsentHit | null {
  if (verdict === 'accept') return null
  // При встречном вторая сторона законно говорит, что остальное её устраивает.
  // Недопустимо только закрыть сделку словами.
  const patterns = verdict === 'counter' ? CLOSING : [...CLOSING, ...ACCEPTING]

  for (const sentence of norm(reply).split(/(?<=[.!?…])\s+/)) {
    if (NOT_A_DEAL.some((re) => re.test(sentence))) continue
    // Условное согласие — это ещё торг, а не договорённость.
    if (w('(если|при условии|в случае|только когда)').test(sentence)) continue
    for (const re of patterns) {
      const m = re.exec(sentence)
      if (!m) continue
      if (NEGATION.test(sentence.slice(0, m.index))) continue
      return { sentence, phrase: m[0] }
    }
  }
  return null
}

/** Что сказать модели, когда она согласилась без решения. */
export function consentCorrection(verdict?: OfferVerdict): string {
  const why =
    verdict === 'counter'
      ? 'Решение системы — встречное предложение, сделка не закрыта.'
      : verdict === 'reject'
        ? 'Решение системы — отказ.'
        : 'Собеседник не прислал пакет условий, решения о согласии не было.'
  return `СИСТЕМА: в твоей реплике есть согласие на условия. ${why} Перепиши реплику: без «принимаю», «согласен», «договорились». Смысл и тон сохрани. Верни тот же JSON.`
}

/** Что сказать модели, когда она проговорила то, о чём её не спрашивали. */
export function leakCorrection(labels: string[]): string {
  return `СИСТЕМА: в твоей реплике прозвучало то, что ты пока скрываешь: ${labels.join('; ')}. Собеседник этого не заслужил своим вопросом. Перепиши реплику: держись публичной позиции, скрытое не называй и не намекай на него. Тон сохрани. Верни тот же JSON.`
}
