/**
 * Вопрос в лоб — не разведка.
 *
 * Скрытый интерес открывается типом вопроса, а тип размечает модель. На живом
 * прогоне «Скажите прямо, чего вы на самом деле хотите?» ушло как ситуационный
 * вопрос SPIN и открыло интерес. Продукт обещает обратное — общий вопрос не
 * открывает ничего, — и это первое, что проверит человек, решивший схитрить.
 *
 * Поэтому прямая просьба назвать интересы распознаётся кодом, и акты SPIN с
 * неё снимаются до того, как движок решает, что раскрыто. Список узкий: он
 * ловит требование выдать интересы, а не любой вопрос со словом «хотите».
 * «Что для вас будет самым болезненным, если проект сдвинется?» — настоящий
 * вопрос и проходит.
 */

const L = '(?<![а-яa-z0-9])'
const R = '(?![а-яa-z0-9])'

const DIRECT_ASK = [
  // «Скажите прямо», «назовите честно»
  new RegExp(L + '(скажите|назовите|признайтесь|говорите|расскажите)\\s+(мне\\s+|нам\\s+)?(прямо|честно|откровенно|как есть)' + R),
  // «Чего вы на самом деле хотите»
  new RegExp(L + '(чего|что)\\s+(же\\s+)?(вы|вам)\\s+(на самом деле|реально|по-настоящему|в действительности|в итоге|вообще)\\s+(хотите|нужно|надо|добиваетесь)' + R),
  // «Какие у вас настоящие интересы»
  new RegExp(L + '(какие|каковы)\\s+(у\\s+вас\\s+|ваши\\s+)?(настоящие|истинные|скрытые|реальные|подлинные)\\s+(интересы|цели|мотивы|причины|потребности)' + R),
  // «Чего вы хотите?» целиком, без предмета
  /^\s*(ну\s+|так\s+)?(и\s+)?(чего|что)\s+(же\s+)?вы\s+хотите\s*[?!.]*\s*$/,
]

export function isDirectAsk(text: string): boolean {
  const t = text.toLowerCase().replace(/ё/g, 'е')
  return DIRECT_ASK.some((re) => re.test(t))
}
