/**
 * Распознавание речевых актов запасным движком.
 *
 * По этой разметке запасной движок выбирает реплику, поэтому промах читается
 * игроком как ответ невпопад. Проверяются канонические вопросы и правдоподобные
 * перефразировки: «кто у вас подписывает», просьба без знака вопроса
 * («Расскажите, как у вас с графиком»).
 *
 * Обратная половина важна не меньше: пустая вежливость не должна выглядеть
 * разведкой, иначе скрытый интерес открывается тем, кто ничего не спросил.
 */
import { scenarios } from '@/lib/scenarios'
import { detectActs } from '@/lib/llm/offline'
import type { SpeechAct } from '@/lib/types'

let failed = 0

/** Вопросы, каждый из которых обязан попасть в акт, открывающий интерес этого кейса. */
const UNLOCKING: Record<string, string[]> = {
  'resident-attraction': [
    'Если мощность придёт позже, чем вы рассчитываете, что это значит для монтажа линии?',
    'Что произойдёт с запуском, если подключение сдвинется за март?',
    'Как у вас было с набором людей на прошлой площадке?',
    'Расскажите, как сейчас устроен ваш график выхода на мощность',
    'Кто в итоге утверждает выбор площадки — вы или совет директоров?',
    'Что должно быть в предложении, чтобы вам было чем защитить его перед советом?',
    'Насколько важно для вас зафиксировать срок подключения?',
  ],
  'contractor-delay': [
    'Что произойдёт с вашими субподрядчиками, если график сдвинется ещё на месяц?',
    'Расскажите, как сейчас устроено финансирование работ?',
    'Что вам мешает выйти на прежний темп?',
    'Кто у вас подписывает изменения к договору?',
    'Что бы вам дало поэтапное закрытие работ?',
  ],
  'resident-default': [
    'Что конкретно должно произойти до конца квартала, чтобы план перестал быть обещанием?',
    'Расскажите, как сейчас обстоят дела с финансированием',
    'Что произойдёт с проектом, если мы зафиксируем публичное признание срыва?',
    'Кто принимает решение о дополнительном капитале — вы или банк?',
    'Что бы вам дало сокращение участка под первую очередь?',
  ],
  'supplier-hike': [
    'Что произойдёт с вашей загрузкой, если мы уменьшим объём вдвое?',
    'Расскажите, как сейчас устроено планирование производства',
    'Что вам мешает удержать цену?',
    'По отраслевым индексам сырьё выросло на 6%, а не на 15%',
    'Что бы вам дал контракт на три года вместо одного?',
  ],
}

console.log('Вопросы, открывающие интересы\n')
let hits = 0
let total = 0
for (const s of scenarios) {
  const unlockers = new Set<SpeechAct>(s.hiddenInterests.flatMap((h) => h.unlockedBy))
  for (const q of UNLOCKING[s.id] ?? []) {
    total++
    const acts = detectActs(q)
    const ok = acts.some((a) => unlockers.has(a))
    if (ok) hits++
    else {
      failed++
      console.log(`  ✗ ${s.id}: [${acts.join(', ') || 'ничего'}] — ${q}`)
    }
  }
}
console.log(`  распознано ${hits} из ${total}`)

console.log('\nРеплики, которые разведкой НЕ являются\n')
const EMPTY = [
  'Добрый день, рад встрече.',
  'Понимаю вас.',
  'Хорошо, давайте посмотрим.',
  'Спасибо, понятно.',
  'Да, согласен.',
  'Ясно.',
]
for (const q of EMPTY) {
  const acts = detectActs(q)
  const probing = acts.some((a) => a.startsWith('spin_') || a === 'authority_check')
  if (probing) {
    failed++
    console.log(`  ✗ пустая реплика распознана как разведка: [${acts.join(', ')}] — ${q}`)
  }
}
console.log(`  проверено ${EMPTY.length}, ложных срабатываний ${failed ? 'есть' : 'нет'}`)

console.log('\nОтдельные акты')
const EXACT: [string, SpeechAct][] = [
  ['Если мы сдвинем срок, вы готовы зафиксировать объём?', 'conditional_offer'],
  ['По отраслевым индексам рост составил 6%', 'objective_criterion'],
  ['Правильно ли я понимаю, что срок для вас важнее ставки?', 'active_listening'],
  ['Это несерьёзно, вы просто не понимаете экономику', 'personal_attack'],
  ['Это наше последнее предложение', 'walkaway_signal'],
]
for (const [text, act] of EXACT) {
  const acts = detectActs(text)
  if (!acts.includes(act)) {
    failed++
    console.log(`  ✗ ожидался ${act}, получено [${acts.join(', ') || 'ничего'}] — ${text}`)
  }
}
if (!failed) console.log('  ✓ все акты на месте')

console.log('\n' + '═'.repeat(70))
if (failed) {
  console.error(`ОШИБОК: ${failed}`)
  process.exit(1)
}
console.log('✓ запасной движок понимает, о чём его спросили')
